import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=(path)=>fs.readFileSync(path,'utf8')

assert(/<version>0[.](?:4[6-9]|[5-9]\d)[.]\d+<\/version>/.test(read('appinfo/info.xml')))
assert(/VERSION = '0[.](?:4[6-9]|[5-9]\d)[.]\d+'/.test(read('lib/AppInfo/Application.php')))
for(const command of ['Backup','Restore','Retention']) assert(read('appinfo/info.xml').includes(`Command\\${command}`),`${command}-Kommando fehlt`)
const routes=read('appinfo/routes.php')
for(const route of ['operations/retention','operations/audit-integrity','export.json']) assert(routes.includes(route),`Route ${route} fehlt`)
const migration=read('lib/Migration/Version1800Date20260906000000.php')
for(const column of ['retention_hold','retention_due_at','anonymized_at','previous_hash','event_hash']) assert(migration.includes(column),`Migration enthält ${column} nicht`)
const retention=read('lib/Service/RetentionPolicyService.php')
assert(retention.includes('preview')&&retention.includes('BESTATTER')===false,'Aufbewahrungsservice bleibt unabhängig vom CLI-Bestätigungscode')
assert(retention.includes("createNamedParameter('ABGESCHLOSSEN')")&&retention.includes("createNamedParameter('STORNIERT')"),'nur abgeschlossene/stornierte Fälle dürfen fällig werden')
assert(!retention.includes('PARAM_STR_ARRAY'),'Aufbewahrungsvorschau darf keine in Nextcloud 34 fehlende Array-Konstante verwenden')
const audit=read('lib/Service/AuditService.php')
assert(audit.includes("hash('sha256'")&&audit.includes('verifyIntegrity'),'Audit-Verkettung fehlt')
assert(/password\|secret\|token/.test(audit),'Audit-Minimierung fehlt')
const backup=read('lib/Service/BackupService.php')
assert(backup.includes('targetEmpty')&&backup.includes('sha256')&&backup.includes('beginTransaction'),'sicherer Restore fehlt')
for(const doc of ['docs/BETRIEBSHANDBUCH.md','docs/AUFBEWAHRUNG-UND-LOESCHUNG.md','docs/BACKUP-RESTORE.md','docs/WIEDERHERSTELLUNGSTEST.md','docs/ENTWICKLUNG.md']) assert(fs.existsSync(doc),`${doc} fehlt`)
assert(read('src/modules/documents.js').includes('export-case'),'Fall-Export ist im UI nicht erreichbar')
console.log('0.46.x Betriebsreife: statische Prüfungen erfolgreich.')
